# Автоматични тестове на stb-check.ps1: всеки случай посочва кои правила трябва (и не трябва) да се задействат.
# Употреба: powershell -ExecutionPolicy Bypass -File tests\run-tests.ps1
$check = Join-Path $PSScriptRoot '..\scripts\stb-check.ps1'
try { [Console]::OutputEncoding = [Text.Encoding]::UTF8 } catch {}

# Текст | правила, които ТРЯБВА да има | правила, които НЕ трябва да има
$cases = @(
    @('1. Затегнете гайката с 25 N·m.', @(), @('2.1', '4.1', '4.2', '4.6', '1.1'), @('mechanics')),
    @('1. Свържете кабела към конектора и затегнете болта.', @('4.2'), @()),
    @('1. Изключете захранването; почистете филтъра.', @('4.6'), @()),
    @('1. Болтът се затяга.', @('2.1', '2.5/2.6'), @()),
    @('1. Затегнете гайката, като внимавате.', @(), @('2.1')),
    @('1. Използвайте болт и/или винт.', @('4.10'), @()),
    @('1. Затегнете три болта.', @('7.1'), @()),
    @('1. Затегнете около 5 болта.', @('7.5'), @()),
    @('1. Затегнете болта правилно.', @('1.1'), @()),
    @('Помпата била включена.', @('2.4'), @()),
    @('1. Ако клапанът е отворен, затворете клапана.', @(), @('4.5')),
    @('1. Затворете клапана, ако е отворен.', @('4.5'), @()),
    @('Конекторът, който е жълт, е за захранването.', @('3.5 ⚠'), @()),
    @('1. Свържете кабела и го закрепете.', @('3.6 ⚠'), @()),
    @('1. Използвайте гаечен ключ.', @('1.1'), @(), @()),
    @('1. Използвайте гаечен ключ.', @(), @('1.1'), @('mechanics')),
    @('1. Използвайте ключ.', @('1.1'), @(), @('mechanics')),
    @('1. Проверете веригата.', @('1.6'), @(), @('all')),
    @('1. Проверете веригата.', @(), @('1.6'), @('mechanics')),
    @('1. Стартирайте услугата.', @(), @('1.1'), @('it')),
    @('1. Стартирайте услугата.', @('1.1'), @(), @())
)
$fail = 0
foreach ($c in $cases) {
    $dom = if ($c.Count -gt 3) { $c[3] } else { @() }; $out = & $check -Text $c[0] -Kind procedure -Domain $dom 2>&1 | Out-String
    foreach ($r in $c[1]) {
        if ($out -notmatch [regex]::Escape($r)) { "НЕУСПЕХ: очаквано правило $r не се задейства: $($c[0])"; $fail++ }
    }
    foreach ($r in $c[2]) {
        if ($out -match "\s$([regex]::Escape($r))\s") { "НЕУСПЕХ: правило $r не трябваше да се задейства: $($c[0])"; $fail++ }
    }
}
if ($fail -eq 0) { "Всички $($cases.Count) теста минаха." } else { "Неуспешни проверки: $fail"; exit 1 }
